  @override
  Uint8List qmc1Decrypt(Uint8List data) {
    // 对齐Python版 qmc1：i<=0x7FFF 与 i>0x7FFF 走不同取模分支。
    final Uint8List output = Uint8List.fromList(data);
    for (int i = 0; i < output.length; i++) {
      final int keyIndex = i > 0x7fff ? ((i % 0x7fff) & 0x7f) : (i & 0x7f);
      output[i] = output[i] ^ _qmc1PrivKey[keyIndex];
    }
    return output;
  }

  @override
  tripledes.TripleDesSchedule tripledesKeySetup({
    required Uint8List key,
    required tripledes.TripleDesMode mode,
  }) {
    return tripledes.tripledesKeySetup(key: key, mode: mode);
  }

  @override
  Uint8List tripledesCrypt({
    required Uint8List data,
    required tripledes.TripleDesSchedule schedule,
  }) {
    return tripledes.tripledesCrypt(data: data, schedule: schedule);
  }
